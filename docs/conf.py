"""Sphinx configuration for the kexp documentation site.

The API reference is generated by sphinx-autoapi, which reads the source files
without importing them. The build therefore needs none of the lab environment
(ARTIQ, camera drivers, Windows-only packages) and runs on a plain GitHub runner.
"""

project = "kexp"
author = "Weld Lab, UCSB"
copyright = "Weld Lab, UCSB"

extensions = [
    "myst_parser",
    "autoapi.extension",
    "sphinx.ext.napoleon",
    "sphinx.ext.intersphinx",
    "sphinx_copybutton",
]

exclude_patterns = ["_build", "Thumbs.db", ".DS_Store"]

# -- Markdown pages (MyST) ----------------------------------------------------
myst_enable_extensions = ["colon_fence", "deflist"]
myst_heading_anchors = 3

# -- API reference (sphinx-autoapi) -------------------------------------------
autoapi_dirs = ["../kexp"]
autoapi_root = "api"
autoapi_add_toctree_entry = False
# Several folders have no __init__.py; without this their modules are listed at
# the top level instead of under kexp.
autoapi_python_use_implicit_namespaces = True
# experiments/ holds several hundred run scripts; they are not an API.
# objective_stage_gui.py does not parse (unfinished since 2024) and one file that
# fails to parse stops the whole build.
autoapi_ignore = [
    "*/experiments/*",
    "*/_bat/*",
    "*/__pycache__/*",
    "*/objective_stages/objective_stage_gui.py",
]
autoapi_options = [
    "members",
    "undoc-members",
    "show-inheritance",
    "show-module-summary",
]
autoapi_member_order = "bysource"
autoapi_python_class_content = "both"

# sphinx-autoapi reads the source without importing it, so names re-exported
# from packages it cannot see are reported; that is expected here.
suppress_warnings = ["autoapi.python_import_resolution"]

# -- Links to other documentation ---------------------------------------------
intersphinx_mapping = {
    "python": ("https://docs.python.org/3", None),
    "numpy": ("https://numpy.org/doc/stable", None),
    "wax": ("https://ucsb-amo.github.io/wax", None),
}
intersphinx_timeout = 10

# -- HTML ---------------------------------------------------------------------
html_theme = "furo"
